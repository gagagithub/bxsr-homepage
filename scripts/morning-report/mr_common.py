def trusted_src(src):
    return any(k in str(src or "") for k in TRUSTED_MEDIA)

# ---------- 数字溯源工具(2026-08-05 起只用于报警, 不拦截) ----------
def _tokens(s):
    """提取文本里的数字 token(含小数)。"""
    return set(re.findall(r"\d+(?:\.\d+)?", re.sub(r"<[^>]+>", "", str(s or ""))))

def _isnum(s):
    try:
        float(s); return True
    except (TypeError, ValueError):
        return False

def _unsourced(text, source_tokens):
    """返回 text 里无法在 source_tokens 溯源的数字集合(空=全部有源)。
    ⚠两档放宽,都要求「数值真的对得上」,不给编造留口子:
    ①同一个数的不同写法: 标题「1.6%」↔原文「1.60%」、「7.0元」↔「7元」——数值相等即有源
      (2026-07-31 加: 少了这档, 当天标题写 1.6 而原文写 1.60 被误判成编造, 标题回退成日期版);
    ②整数容许四舍五入/取整命中原文小数: 「油价涨6%」↔「6.17%」、「40年新低」↔「39.8」;
    但小数 vs 小数仍须数值相等(6.78 ↔ 6.7801 照样拦)。
    ⚠已知盲区: 中文数字(「五年期」↔「5年期」)不认, 8-05 因此误杀过一次 —— 也正因为闸门
    分不清"编造"和"合理改写", 崔伟 8-05 拍板全部改只报警(见 memory feedback_no_auto_content_gates)。"""
    src_floats = [float(o) for o in source_tokens if _isnum(o)]
    bad = set()
    for t in _tokens(text):
        if t in source_tokens:
            continue
        if _isnum(t):
            tv = float(t)
            if any(o == tv for o in src_floats):
                continue  # 同一个数的不同写法(1.6↔1.60), 数值相等
            if "." not in t and any(round(o) == tv or int(o) == tv for o in src_floats):
                continue  # 原文小数四舍五入/取整后=标题整数, 视为口语化后的真数字
        bad.add(t)
    return bad

# ---------- 地方性判定(全国号不拿一个省的政策做标题, 2026-07-30) ----------
_PROV_RE = re.compile(
    r"北京|天津|上海|重庆|河北|山西|辽宁|吉林|黑龙江|江苏|浙江|安徽|福建|江西|山东|河南|"
    r"湖北|湖南|广东|海南|四川|贵州|云南|陕西|甘肃|青海|内蒙古|广西|西藏|宁夏|新疆|"
    r"深圳|广州|杭州|南京|成都|武汉|西安|苏州|青岛|长沙|郑州|合肥|济南|福州|厦门|宁波")
_NATIONWIDE_RE = re.compile(
    r"全国|各地|多地|多省|各省|31个省|人社部|财政部|国家医保局|国家卫健委|民政部|国务院|"
    r"中国人民银行|央行|金融监管总局|国家金融监督管理总局|国家发展改革委|国家税务总局|"
    r"中办|国办|中共中央")   # ⚠别漏中办/国办: 少了它, "长护险全国铺开"这种全国性头条会被误拦

def title_is_local(title, one):
    """标题挑了地方性政策 → 返回地名; 否则返回 ''。one=标题所引那条原文。"""
    m = _PROV_RE.search(title or "")
    if not m:
        return ""
    if _NATIONWIDE_RE.search(one or ""):      # 原文本身就是全国性的, 标题顺带提个省份不算
        return ""
    return m.group(0)

